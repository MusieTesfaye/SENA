//! Poseidon over the BN254 scalar field, as circom's `Poseidon(n)` computes it.
//!
//! This is the hash the Aptos Keyless circuit uses for its public inputs, the
//! identity commitment and the OAuth `nonce`. It must agree with circomlib bit
//! for bit: a single differing constant would make every honest proof fail, or
//! — worse — make the Aptos L1 verifier and the node disagree.
//!
//! The permutation is the straightforward reference form (add round constants,
//! S-box, multiply by the MDS matrix), not an optimised variant, so that the
//! Move implementation in `move/sena/sources/poseidon.move` can mirror it line
//! for line. Constants are loaded from `poseidon_constants.bin`, generated by
//! `scripts/gen_poseidon_constants.py` from the circomlib constants Aptos
//! ships, and pinned by SHA-256 in the tests below.

use std::sync::LazyLock;

use ark_bn254::Fr;
use ark_ff::{Field, PrimeField, Zero};

/// The most inputs one call can absorb (state width 17).
pub const MAX_INPUTS: usize = 16;

/// Full rounds, for every width.
const FULL_ROUNDS: usize = 8;

static CONSTANTS_BIN: &[u8] = include_bytes!("poseidon_constants.bin");

/// Round constants and MDS matrix for one state width.
struct WidthConstants {
    partial_rounds: usize,
    /// `(FULL_ROUNDS + partial_rounds) * t` constants, round-major.
    round_constants: Vec<Fr>,
    /// `t * t` entries, row-major.
    mds: Vec<Fr>,
}

/// Constants for t = 2..=17, indexed by `t - 2`.
static CONSTANTS: LazyLock<Vec<WidthConstants>> = LazyLock::new(load_constants);

fn read_u16(bytes: &[u8], at: usize) -> usize {
    usize::from(u16::from_le_bytes([bytes[at], bytes[at + 1]]))
}

fn load_constants() -> Vec<WidthConstants> {
    let mut at = 0;
    let mut out = Vec::with_capacity(MAX_INPUTS);
    for expected_t in 2..=MAX_INPUTS + 1 {
        let t = read_u16(CONSTANTS_BIN, at);
        let partial_rounds = read_u16(CONSTANTS_BIN, at + 2);
        at += 4;
        assert_eq!(t, expected_t, "poseidon constants are out of order");
        let mut take = |n: usize| -> Vec<Fr> {
            (0..n)
                .map(|_| {
                    let fr = Fr::from_le_bytes_mod_order(&CONSTANTS_BIN[at..at + 32]);
                    at += 32;
                    fr
                })
                .collect()
        };
        let round_constants = take((FULL_ROUNDS + partial_rounds) * t);
        let mds = take(t * t);
        out.push(WidthConstants {
            partial_rounds,
            round_constants,
            mds,
        });
    }
    assert_eq!(at, CONSTANTS_BIN.len(), "trailing poseidon constant bytes");
    out
}

/// Why a hash could not be computed.
#[derive(Clone, Copy, PartialEq, Eq, Debug, thiserror::Error)]
pub enum PoseidonError {
    /// Poseidon here absorbs between 1 and [`MAX_INPUTS`] field elements.
    #[error("poseidon takes 1 to {MAX_INPUTS} inputs, got {0}")]
    WrongArity(usize),
}

/// Hashes 1 to 16 field elements, matching circomlib's `Poseidon(n)`.
///
/// # Errors
///
/// Returns [`PoseidonError::WrongArity`] for zero or more than 16 inputs.
pub fn hash(inputs: &[Fr]) -> Result<Fr, PoseidonError> {
    let n = inputs.len();
    if n == 0 || n > MAX_INPUTS {
        return Err(PoseidonError::WrongArity(n));
    }
    let t = n + 1;
    let c = &CONSTANTS[n - 1];

    let mut state = Vec::with_capacity(t);
    state.push(Fr::zero());
    state.extend_from_slice(inputs);

    let rounds = FULL_ROUNDS + c.partial_rounds;
    let half_full = FULL_ROUNDS / 2;
    let mut mixed = vec![Fr::zero(); t];
    for round in 0..rounds {
        for (i, s) in state.iter_mut().enumerate() {
            *s += c.round_constants[round * t + i];
        }
        let full = round < half_full || round >= half_full + c.partial_rounds;
        if full {
            state.iter_mut().for_each(sbox);
        } else {
            sbox(&mut state[0]);
        }
        for (i, out) in mixed.iter_mut().enumerate() {
            let row = &c.mds[i * t..(i + 1) * t];
            *out = row.iter().zip(&state).map(|(m, s)| *m * s).sum();
        }
        std::mem::swap(&mut state, &mut mixed);
    }
    Ok(state[0])
}

/// x ↦ x⁵.
fn sbox(x: &mut Fr) {
    let x2 = x.square();
    *x *= x2.square();
}

